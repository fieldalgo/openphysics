"""Regenerate physmat/_tables.py from a local refractiveindex.info database (CC0 1.0).

Usage: python tools/build_tables.py /path/to/refractiveindex.info-database/database
"""
import sys
from pathlib import Path

import re
import numpy as np
import yaml

root = Path(sys.argv[1])
SOURCES = {
    # key: (relative yaml path, wavelength window in um to keep)
    "Au_Johnson": ("main/Au/nk/Johnson.yml", (0.18, 2.0)),
    "Ag_Johnson": ("main/Ag/nk/Johnson.yml", (0.18, 2.0)),
    "Cu_Johnson": ("main/Cu/nk/Johnson.yml", (0.18, 2.0)),
    "Al_Rakic": ("main/Al/nk/Rakic.yml", (0.2, 12.0)),
    "Si_Green2008": ("main/Si/nk/Green-2008.yml", (0.2, 1.5)),
    "H2O_Hale": ("main/H2O/nk/Hale.yml", (0.2, 200.0)),
}
out = ['# Data from the refractiveindex.info database; see NOTICE.',
       '# SPDX-License-Identifier: CC0-1.0',
       '',
       '"""Tabulated n,k data copied from the refractiveindex.info database (CC0 1.0, public domain).',
       '', 'Generated by tools/build_tables.py; do not edit by hand. Columns: wavelength_um, n, k.',
       'Please cite: M. N. Polyanskiy, Sci. Data 11, 94 (2024).', '"""', '', 'import numpy as np', '', 'REFERENCES = {}', 'TABLES = {}', '']
for key, (rel, (lo, hi)) in SOURCES.items():
    doc = yaml.safe_load((root / "data" / rel).read_text(encoding="utf-8"))
    block = [b for b in doc["DATA"] if b["type"].strip() == "tabulated nk"][0]
    arr = np.array([r.split() for r in block["data"].strip().splitlines() if r.strip()], dtype=float)
    arr = arr[(arr[:, 0] >= lo) & (arr[:, 0] <= hi)]
    ref = " ".join(doc["REFERENCES"].split())

    ref = re.sub(r"<[^>]+>", "", ref)
    out.append(f"REFERENCES[{key!r}] = {ref!r}")
    rows = ",\n".join("    [" + ", ".join(f"{v:.6g}" for v in r) + "]" for r in arr)
    out.append(f"TABLES[{key!r}] = np.array([\n{rows}\n])\n")
Path(__file__).resolve().parent.parent.joinpath("physmat", "_tables.py").write_text("\n".join(out))
print("wrote _tables.py")
