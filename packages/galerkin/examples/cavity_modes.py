"""M3b validation: resonant modes of a rectangular PEC cavity (3D Maxwell).

Problem:  curl curl E = k^2 E  in  [0,a] x [0,b] x [0,c],   n x E = 0 on the walls

Exact spectrum
--------------
Separating variables gives standing waves

    E_x = A cos(m pi x/a) sin(n pi y/b) sin(p pi z/c)
    E_y = B sin(m pi x/a) cos(n pi y/b) sin(p pi z/c)
    E_z = C sin(m pi x/a) sin(n pi y/b) cos(p pi z/c)

with k^2 = (m pi/a)^2 + (n pi/b)^2 + (p pi/c)^2. Each component survives only if
its two sine factors are not identically zero, and div E = 0 removes one further
amplitude whenever it is a non-trivial condition. That counting — done twice
below, once through the textbook TE/TM index restrictions and once directly from
the amplitudes — fixes the MULTIPLICITY of every eigenvalue. Multiplicities are
where a cavity validation quietly goes wrong: one missing mode shifts the whole
comparison by one and every number afterwards looks plausible.

What is being tested
--------------------
Edge elements are the right discretization because the discrete complex is exact:
the kernel of the discrete curl is precisely the span of the discrete gradients.
On a simply connected domain with PEC walls that pins the kernel dimension to the
number of interior nodes — an exact integer, checked here, and the structural
reason no spurious modes appear between the physical ones.

The TE111/TM111 pair comes out split, and it is worth being precise about why,
because the obvious explanation is wrong. It is not that the Kuhn subdivision
has a preferred diagonal — that would imply a better mesh could fix it. A box
with three distinct side lengths has point group Z2^3, generated by the three
mid-plane reflections; the group is abelian, so every irreducible representation
is one-dimensional and NO two-fold degeneracy can be symmetry-enforced. Under
x -> a - x the amplitude triple (A, B, C) maps to (-1)^(m+1) (A, B, C), a scalar
on the whole eigenspace, so both partners live in the same one-dimensional
representation. The degeneracy is accidental — two polarizations sharing one
wavevector — and no mesh of the box can protect it. Measured: a randomly
jittered mesh, which has no structure whatsoever, splits the pair by the same
amount as the Kuhn mesh does.

That is the exact opposite of M3a, where the m = +-1 and m = +-2 pairs ARE
protected, by the C_n rotational symmetry that disk_mesh reproduces exactly, and
where the residual splitting was consequently 1.2e-14. Knowing which of those two
situations a mesh is in is the whole difference between reading a splitting as
physics and reading it as discretization error.
"""

import numpy as np
import scipy.sparse as sp
import scipy.sparse.linalg as spla

from galerkin import (box_mesh, Mesh3D, EdgeSpace3D, assemble_curlcurl_3d,
                      assemble_edge_mass_3d, assemble_edge_grad_3d,
                      assemble_stiffness_3d, assemble_mass_3d)

A_BOX, B_BOX, C_BOX = 1.0, 0.8, 0.6


# ---------------------------------------------------------------- analytic ---
def _k2(m, n, p):
    return (m * np.pi / A_BOX) ** 2 + (n * np.pi / B_BOX) ** 2 + (p * np.pi / C_BOX) ** 2


def _mult_te_tm(m, n, p):
    """Textbook index restrictions: TE_mnp needs (m,n) != (0,0) and p >= 1;
    TM_mnp needs m >= 1 and n >= 1."""
    labels = []
    if not (m == 0 and n == 0) and p >= 1:
        labels.append(f"TE{m}{n}{p}")
    if m >= 1 and n >= 1:
        labels.append(f"TM{m}{n}{p}")
    return labels


def _mult_amplitudes(m, n, p):
    """Independent count: allowed standing-wave amplitudes minus the divergence
    constraint, when that constraint is not vacuous."""
    allowed = [(n >= 1 and p >= 1, m),          # E_x, constraint coefficient m pi/a
               (m >= 1 and p >= 1, n),          # E_y,                      n pi/b
               (m >= 1 and n >= 1, p)]          # E_z,                      p pi/c
    live = [coef for ok, coef in allowed if ok]
    if not live:
        return 0
    return len(live) - (1 if any(c >= 1 for c in live) else 0)


def exact_spectrum(nmax=6):
    """[(k^2, multiplicity, labels)] sorted ascending, with the count cross-checked."""
    table = {}
    for m in range(nmax + 1):
        for n in range(nmax + 1):
            for p in range(nmax + 1):
                labels = _mult_te_tm(m, n, p)
                assert len(labels) == _mult_amplitudes(m, n, p), \
                    f"the two mode counts disagree at (m,n,p)=({m},{n},{p})"
                if not labels:
                    continue
                key = round(_k2(m, n, p), 8)
                entry = table.setdefault(key, [0, []])
                entry[0] += len(labels)
                entry[1] += labels
    return sorted((k, v[0], sorted(set(v[1]))) for k, v in table.items())


def exact_flat(n_take=8):
    out = []
    for k2, mult, labels in exact_spectrum():
        out += [(k2, "/".join(labels))] * mult
    return out[:n_take]


# --------------------------------------------------------------------- FEM ---
def cavity_matrices(nx, ny, nz):
    mesh = box_mesh(A_BOX, B_BOX, C_BOX, nx, ny, nz)
    space = EdgeSpace3D(mesh)
    S = assemble_curlcurl_3d(space)
    M = assemble_edge_mass_3d(space)
    fixed = space.boundary_edge_ids()
    free = np.setdiff1d(np.arange(space.num_edges), fixed)
    n_interior_nodes = mesh.num_nodes - len(mesh.boundary_nodes())
    return mesh, space, free, S[free][:, free].tocsc(), M[free][:, free].tocsc(), \
        n_interior_nodes


def solve_cavity(nx, ny, nz, num_modes=16, sigma=45.0):
    """Resonant k^2 above the gradient kernel, ascending.

    S is symmetric positive semi-definite and M symmetric positive definite, so
    unlike the M3a pencil this one goes straight into eigsh with a shift.
    """
    mesh, space, free, S, M, n_int = cavity_matrices(nx, ny, nz)
    vals, vecs = spla.eigsh(S, k=num_modes, M=M, sigma=sigma, which="LM",
                            v0=np.ones(S.shape[0]),
                            ncv=min(S.shape[0], max(6 * num_modes, 80)),
                            maxiter=50000)
    keep = vals > 1e-6 * np.abs(vals).max()          # drop the gradient kernel
    order = np.argsort(vals[keep])
    return mesh, space, free, vals[keep][order], vecs[:, keep][:, order]


# ------------------------------------------------------------------- gates ---
def check_mesh(nx=4, ny=3, nz=3):
    """Conformity and soundness of the Kuhn subdivision."""
    mesh = box_mesh(A_BOX, B_BOX, C_BOX, nx, ny, nz)
    uniq, count = mesh.faces()
    space = EdgeSpace3D(mesh)
    V, E, F, T = mesh.num_nodes, space.num_edges, len(uniq), mesh.num_tets
    vol = mesh.volumes()
    n_bf, n_over = int((count == 1).sum()), int((count > 2).sum())
    expect_bf = 4 * (nx * ny + ny * nz + nz * nx)
    print("Kuhn subdivision soundness:")
    print(f"  volume {vol.sum():.12f} (exact {A_BOX*B_BOX*C_BOX})   "
          f"min element volume {vol.min():.2e}")
    print(f"  boundary faces {n_bf} (expected {expect_bf}), faces shared by >2 tets "
          f"{n_over}, Euler V-E+F-T = {V-E+F-T}")
    assert abs(vol.sum() - A_BOX * B_BOX * C_BOX) < 1e-12, "volume wrong"
    assert vol.min() > 0, "inverted element"
    assert n_over == 0 and n_bf == expect_bf, "mesh is not conforming"
    assert V - E + F - T == 1, "Euler characteristic wrong for a ball"

    # Quality is refinement-invariant because the subdivision is self-similar: the
    # constant in the interpolation estimate is the same at every level, which is
    # what lets a convergence rate be read off at face value.
    ranges = []
    for m in (1, 2, 4):
        a = box_mesh(A_BOX, B_BOX, C_BOX, 5 * m, 4 * m, 3 * m).dihedral_angles()
        ranges.append((a.min(), a.max()))
    print(f"  dihedral angles {ranges[0][0]:.4f} to {ranges[0][1]:.4f} degrees, "
          f"identical at every refinement level: "
          f"{all(np.allclose(r, ranges[0]) for r in ranges)}")
    assert all(np.allclose(r, ranges[0]) for r in ranges), "quality drifts under refinement"
    assert ranges[0][1] < 179.0, "flat element — the maximum-angle condition fails"


def check_whitney_identities(nx=3, ny=3, nz=2, tol=1e-11):
    """Exact identities of the discrete complex, whatever the mesh or coefficient.

    grad phi_n lies exactly in the Whitney edge space, its dof on edge (lo -> hi)
    being phi(hi) - phi(lo), so the node-to-edge incidence matrix C is a discrete
    gradient and, for any per-element c,

        G(c) = M_t(c) C        S(c) C = 0        K(c) = C^T M_t(c) C

    These tie every 3D assembly routine to every other in one shot, orientation
    signs included. An orientation error still gives a plausible spectrum; it
    cannot give these.
    """
    mesh = box_mesh(A_BOX, B_BOX, C_BOX, nx, ny, nz)
    space = EdgeSpace3D(mesh)
    c = 0.5 + np.arange(mesh.num_tets) % 7
    S = assemble_curlcurl_3d(space, c)
    Mt = assemble_edge_mass_3d(space, c)
    G = assemble_edge_grad_3d(space, c)
    K = assemble_stiffness_3d(mesh, c)

    e = np.arange(space.num_edges)
    lo, hi = space.edges[:, 0], space.edges[:, 1]
    C = sp.coo_matrix((np.r_[np.ones(len(e)), -np.ones(len(e))],
                       (np.r_[e, e], np.r_[hi, lo])),
                      shape=(space.num_edges, mesh.num_nodes)).tocsr()

    print("Whitney identities (3D edge/nodal assembly consistency):")
    for name, resid, scale in (("G - M_t C", abs(G - Mt @ C).max(), abs(G).max()),
                               ("S C", abs(S @ C).max(), abs(S).max()),
                               ("K - C^T M_t C", abs(K - C.T @ Mt @ C).max(),
                                abs(K).max())):
        print(f"  ||{name}||_max = {resid:.2e}   relative {resid/scale:.1e}")
        assert resid < tol * scale, f"identity {name} violated"


def check_degeneracy_is_accidental(m=3, amplitude=0.5, seed=7):
    """The TE111/TM111 split is not a Kuhn artefact — no mesh can remove it.

    The group-theoretic argument is in the module docstring; this is its
    empirical half. Jitter the interior nodes at random, destroying every trace
    of structure while keeping the box exact and the connectivity conforming, and
    the pair splits by the same amount. A split that a structure-free mesh
    reproduces is not caused by the structure.
    """
    shape = (5 * m, 4 * m, 3 * m)
    base = box_mesh(A_BOX, B_BOX, C_BOX, *shape)

    rng = np.random.default_rng(seed)
    nodes = base.nodes.copy()
    on_wall = np.zeros(len(nodes), dtype=bool)
    for tag in base.boundary:
        on_wall[base.boundary[tag]] = True
    h = np.array([A_BOX, B_BOX, C_BOX]) / np.array(shape)
    nodes[~on_wall] += (rng.random((int((~on_wall).sum()), 3)) - 0.5) * amplitude * h
    jittered = Mesh3D(nodes, base.tets.copy(), dict(base.boundary))
    assert jittered.volumes().min() > 0, "jitter inverted an element"

    splits = []
    for mesh in (base, jittered):
        space = EdgeSpace3D(mesh)
        S = assemble_curlcurl_3d(space)
        M = assemble_edge_mass_3d(space)
        free = np.setdiff1d(np.arange(space.num_edges), space.boundary_edge_ids())
        v = spla.eigsh(S[free][:, free].tocsc(), k=12, M=M[free][:, free].tocsc(),
                       sigma=45.0, which="LM", v0=np.ones(len(free)),
                       ncv=min(len(free), 90), maxiter=50000,
                       return_eigenvectors=False)
        v = np.sort(v[v > 1e-6 * np.abs(v).max()])
        splits.append(abs(v[4] - v[3]))
    ratio = splits[1] / splits[0]
    print(f"TE111/TM111 split, structured vs randomly jittered mesh at h = "
          f"{A_BOX/shape[0]:.4f}:")
    print(f"  Kuhn {splits[0]:.5e}   jittered {splits[1]:.5e}   ratio {ratio:.2f}")
    assert 0.2 < ratio < 5.0, \
        "the split depends strongly on the mesh — then it is not accidental after all"


def check_kernel_dimension(sizes=((2, 2, 2), (3, 3, 2), (4, 3, 3), (5, 4, 3))):
    """dim ker(curl) on the PEC edge space == number of interior nodes.

    Discrete de Rham exactness: on a simply connected domain the kernel of the
    discrete curl is exactly the range of the discrete gradient, and the gradient
    is injective up to constants, so the dimension is an integer read off the mesh.
    Checked densely, which is affordable because the identity is mesh-independent
    and therefore provable on small meshes.
    """
    print("Discrete de Rham exactness — dim ker(curl) vs interior node count:")
    for n in sizes:
        _, _, _, S, _, n_int = cavity_matrices(*n)
        w = np.linalg.eigvalsh(S.toarray())
        n_zero = int((w < 1e-9 * w.max()).sum())
        print(f"  {str(n):>12}: free edges {S.shape[0]:>5}   dim ker {n_zero:>4}   "
              f"interior nodes {n_int:>4}   {'match' if n_zero == n_int else 'MISMATCH'}")
        assert n_zero == n_int, "the discrete complex is not exact"


# -------------------------------------------------------------------- main ---
def main():
    check_mesh()
    check_whitney_identities()
    check_kernel_dimension()
    check_degeneracy_is_accidental()

    flat = exact_flat(8)
    print(f"\nrectangular PEC cavity {A_BOX} x {B_BOX} x {C_BOX} — exact spectrum:")
    for k2, mult, labels in exact_spectrum()[:6]:
        print(f"  k^2 = {k2:>12.7f}   multiplicity {mult}   {' '.join(labels)}")

    levels = [(5 * k, 4 * k, 3 * k) for k in (1, 2, 3, 4)]
    hs, errs, splits, last = [], [], [], None
    print(f"\n{'mesh':>12} {'h':>8} {'tets':>8} {'dofs':>8}   first six k^2")
    for n in levels:
        mesh, space, free, vals, vecs = solve_cavity(*n)
        hs.append(A_BOX / n[0])
        errs.append(np.abs(vals[:6] - [v for v, _ in flat[:6]])
                    / np.array([v for v, _ in flat[:6]]))
        splits.append(abs(vals[4] - vals[3]))       # the exactly-degenerate pair
        last = (mesh, space, free, vals, vecs)
        print(f"{str(n):>12} {hs[-1]:>8.4f} {mesh.num_tets:>8} {len(free):>8}   "
              + "  ".join(f"{v:.4f}" for v in vals[:6]))

    mesh, space, free, vals, vecs = last
    print(f"\nfinest mesh vs exact:")
    print(f"{'mode':>12} {'exact k^2':>14} {'FEM':>14} {'rel err':>10}")
    for (ev, label), fv in zip(flat[:6], vals[:6]):
        print(f"{label:>12} {ev:>14.7f} {fv:>14.7f} {abs(fv-ev)/ev:>10.2e}")
        assert abs(fv - ev) / ev < 5e-3, f"{label} off by {abs(fv-ev)/ev:.2e}"

    # convergence: the non-degenerate modes carry the rate cleanly
    E = np.array(errs)
    print(f"\n{'h':>8} " + "".join(f"{lbl:>13}" for _, lbl in flat[:3])
          + f"{'TE111/TM111':>15}{'split':>11}")
    for i, h in enumerate(hs):
        print(f"{h:>8.4f} " + "".join(f"{E[i, j]:>13.2e}" for j in range(3))
              + f"{E[i, 3]:>15.2e}{splits[i]:>11.2e}")
    rate = np.log(E[-2, :3] / E[-1, :3]) / np.log(hs[-2] / hs[-1])
    srate = np.log(splits[-2] / splits[-1]) / np.log(hs[-2] / hs[-1])
    print(f"\nconvergence rate of the three non-degenerate modes: "
          + "  ".join(f"{r:.2f}" for r in rate) + "  (theory: 2.0)")
    print(f"the TE111/TM111 degeneracy is accidental, so no mesh preserves it; "
          f"the split vanishes at rate {srate:.2f}")
    assert rate.min() > 1.8, f"convergence below second order: {rate}"
    assert srate > 1.8, f"degeneracy splitting not vanishing at second order: {srate:.2f}"
    print(f"\nPASS: cavity spectrum within 5e-3, convergence rate "
          f"{rate.min():.2f} (theory: 2.0), discrete complex exact")

    np.savez("cavity_modes.npz",
             exact=np.array([v for v, _ in flat]),
             labels=np.array([l for _, l in flat]),
             fem=vals[:8], h=np.array(hs), err=E, split=np.array(splits),
             a=A_BOX, b=B_BOX, c=C_BOX)


if __name__ == "__main__":
    main()
