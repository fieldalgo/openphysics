def rib_waveguide(core_width: float = 3.0, core_thickness: float = 1.0,
                  slab_thickness: float = 0.0, domain_width: float = 18.0,
                  substrate_thickness: float = 10.0, cladding_thickness: float = 3.0,
                  lc_core: float = 0.1, lc_far: float = 0.5) -> str:
    """Rib waveguide cross-section as used in the Hadley (2002) benchmark.

    Regions: ``core`` (rib plus the outer slab of thickness ``slab_thickness``),
    ``box`` (substrate below y=0) and ``clad`` (above). Boundary curves are
    named left/right/bottom/top. Lengths in micrometres in the benchmark
    (width 3, thickness 1, slab 0..0.7, wavelength 1.15).
    """
    w, h, t = core_width / 2, core_thickness, slab_thickness
    W, B, C = domain_width / 2, substrate_thickness, cladding_thickness
    if not 0 <= t < h:
        raise ValueError("slab_thickness must be in [0, core_thickness)")
    g = Geo()
    g.default_lc = lc_far
    if t == 0:
        core = [(-w, 0), (w, 0), (w, h), (-w, h)]
        clad = [(-W, 0), (-w, 0), (-w, h), (w, h), (w, 0), (W, 0), (W, C), (-W, C)]
    else:
        core = [(-W, 0), (W, 0), (W, t), (w, t), (w, h), (-w, h), (-w, t), (-W, t)]
        clad = [(-W, t), (-w, t), (-w, h), (w, h), (w, t), (W, t), (W, C), (-W, C)]
    box = [(-W, -B), (W, -B), (W, 0), (-W, 0)]
    g.add_region("core", core, lc=lc_core)
    g.add_region("box", box, lc=lc_far)
    g.add_region("clad", clad, lc=lc_far)
    # size = lc_core on the core, growing linearly to lc_far within 3 core thicknesses
    g.raw("Field[1] = Distance; Field[1].SurfacesList = {1}; Field[1].Sampling = 200;")
    g.raw(f"Field[2] = Threshold; Field[2].InField = 1; Field[2].SizeMin = {_num(lc_core)}; "
          f"Field[2].SizeMax = {_num(lc_far)}; Field[2].DistMin = 0; Field[2].DistMax = {_num(3 * h)};")
    g.raw("Background Field = 2;")
    g.raw("Mesh.MeshSizeExtendFromBoundary = 0; Mesh.MeshSizeFromPoints = 0;")
    return g.render(box_sides(-W, W, -B, C))


def circular_fiber(core_radius: float, domain_radius: float, lc_core: float,
                   lc_clad: float | None = None, core_name: str = "core",
                   clad_name: str = "clad", boundary_name: str = "outer") -> str:
    """Step-index fiber cross-section: circular core inside a circular cladding.

    Regions ``core`` and ``clad``; the outer circle is the physical curve
    ``outer``. Built from exact circle arcs, so mesh nodes lie on the true
    circle (the discretisation error is the usual O(h^2) polygonal one).
    """
    if not 0 < core_radius < domain_radius:
        raise ValueError("need 0 < core_radius < domain_radius")
    lc_clad = lc_core * 4 if lc_clad is None else lc_clad
    a, R = core_radius, domain_radius
    lines = ["// generated by gmshio.geo.circular_fiber",
             f"Point(1) = {{0, 0, 0, {_num(lc_core)}}};"]
    for i, (x, y) in enumerate([(a, 0), (0, a), (-a, 0), (0, -a)], start=2):
        lines.append(f"Point({i}) = {{{_num(x)}, {_num(y)}, 0, {_num(lc_core)}}};")
    for i, (x, y) in enumerate([(R, 0), (0, R), (-R, 0), (0, -R)], start=6):
        lines.append(f"Point({i}) = {{{_num(x)}, {_num(y)}, 0, {_num(lc_clad)}}};")
    lines += ["Circle(1) = {2, 1, 3}; Circle(2) = {3, 1, 4}; Circle(3) = {4, 1, 5}; Circle(4) = {5, 1, 2};",
              "Circle(5) = {6, 1, 7}; Circle(6) = {7, 1, 8}; Circle(7) = {8, 1, 9}; Circle(8) = {9, 1, 6};",
              "Curve Loop(1) = {1, 2, 3, 4}; Plane Surface(1) = {1};",
              "Curve Loop(2) = {5, 6, 7, 8}; Plane Surface(2) = {2, 1};",
              f'Physical Surface("{core_name}") = {{1}};',
              f'Physical Surface("{clad_name}") = {{2}};',
              f'Physical Curve("{boundary_name}") = {{5, 6, 7, 8}};']
    return "\n".join(lines) + "\n"


def box_cavity(a: float, b: float, d: float, lc: float, volume_name: str = "cavity",
               boundary_name: str = "pec") -> str:
    """Rectangular box [0,a]x[0,b]x[0,d] (OpenCASCADE kernel), all six faces tagged ``pec``."""
    return "\n".join([
        "// generated by gmshio.geo.box_cavity",
        'SetFactory("OpenCASCADE");',
        f"Box(1) = {{0, 0, 0, {_num(a)}, {_num(b)}, {_num(d)}}};",
        f"MeshSize {{ PointsOf{{ Volume{{1}}; }} }} = {_num(lc)};",
        f'Physical Volume("{volume_name}") = {{1}};',
        f'Physical Surface("{boundary_name}") = {{1, 2, 3, 4, 5, 6}};',
    ]) + "\n"
